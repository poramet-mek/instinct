'use strict';
const fs = require('fs');
const path = require('path');
const { loadDir } = require('./lesson');

function summary(body) {
  const first = body.split(/\r?\n/).find((l) => l.trim() && !l.startsWith('**')) || '';
  return first.trim().slice(0, 140);
}

function renderIndex(lessons, title) {
  const rows = lessons
    .sort((a, b) => b.seen - a.seen || a.id.localeCompare(b.id))
    .map((l) => `- [${l.id}](${l.id}.md) — ${l.type}${l.tags.length ? ` · ${l.tags.join(', ')}` : ''} · seen ${l.seen} — ${summary(l.body)}`);
  return [`# ${title}`, '', '<!-- generated by `instinct index`; do not edit -->', '', ...(rows.length ? rows : ['(none yet)']), ''].join('\n');
}

function writeIndex(dir, title) {
  const text = renderIndex(loadDir(dir), title);
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'INDEX.md'), text);
  return text;
}

module.exports = { renderIndex, writeIndex };
